def _send_shellcode_over_http(host, port, shellcode, path="/"):
    """Send shellcode as HTTP POST body, return True if connection succeeded."""
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    sock.settimeout(5)
    try:
        sock.connect((host, port))
        http_request = (
            b"POST " + path.encode() + b" HTTP/1.1\r\n"
            b"Host: test\r\n"
            b"Content-Type: application/octet-stream\r\n"
            b"Content-Length: " + str(len(shellcode)).encode() + b"\r\n"
            b"\r\n"
        )
        sock.sendall(http_request + shellcode)

        try:
            sock.recv(1024)
        except socket.timeout:
            pass  # response not required

        return True
    finally:
        sock.close()


def test_x86_shellcode_delivery(dionaea_host, dionaea_ports):
    """Send x86 URLDownloadToFile shellcode and verify dionaea accepts it."""
    port = dionaea_ports["http"]
    assert _send_shellcode_over_http(dionaea_host, port, SHELLCODE_X86)


def test_x64_shellcode_delivery(dionaea_host, dionaea_ports):
    """Send x64 GetPC shellcode and verify dionaea accepts it."""
    port = dionaea_ports["http"]
    assert _send_shellcode_over_http(dionaea_host, port, SHELLCODE_X64, path="/test64")
